// Code-OSS development builds do not replace localize() calls with NLS indices.
// Generate a keyed lookup from the pinned vscode-loc pack for that build only.
import { createRequire } from 'node:module';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const work = process.env.JBRO_EDITOR_WORK;
if (!work) {
	throw new Error('Set JBRO_EDITOR_WORK before generating development translations.');
}
const upstream = join(resolve(work), 'upstream');
const ts = createRequire(join(upstream, 'package.json'))('typescript');
const translations = JSON.parse(readFileSync(join(root, 'extensions/jbro-korean/translations/main.i18n.json'), 'utf8')).contents;
const sourceRoot = join(upstream, 'src');
const messages = new Map();
const conflicts = new Set();
let matched = 0;

function walk(directory) {
	for (const entry of readdirSync(directory)) {
		const file = join(directory, entry);
		if (statSync(file).isDirectory()) {
			if (entry !== 'test' && entry !== 'tests') walk(file);
		} else if (entry.endsWith('.ts') && !entry.endsWith('.d.ts')) {
			readSource(file);
		}
	}
}

function literal(node) {
	return node && (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) ? node.text : undefined;
}

function keyOf(node) {
	const direct = literal(node);
	if (direct !== undefined) return direct;
	if (!node || !ts.isObjectLiteralExpression(node)) return undefined;
	for (const prop of node.properties) {
		if (ts.isPropertyAssignment(prop) && prop.name.getText() === 'key') return literal(prop.initializer);
	}
	return undefined;
}

function readSource(file) {
	const moduleId = relative(sourceRoot, file).split(sep).join('/').replace(/\.ts$/, '');
	const moduleTranslations = translations[moduleId];
	if (!moduleTranslations) return;
	const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
	function visit(node) {
		if (ts.isCallExpression(node) && node.arguments.length >= 2) {
			const callee = node.expression;
			const name = ts.isIdentifier(callee) ? callee.text : ts.isPropertyAccessExpression(callee) ? callee.name.text : '';
			if (name === 'localize' || name === 'localize2') {
				const key = keyOf(node.arguments[0]);
				const english = literal(node.arguments[1]);
				const korean = key === undefined ? undefined : moduleTranslations[key];
				if (english !== undefined && typeof korean === 'string' && korean) {
					const lookup = `${key}\u0000${english}`;
					if (messages.has(lookup) && messages.get(lookup) !== korean) conflicts.add(lookup);
					else messages.set(lookup, korean);
					matched++;
				}
			}
		}
		ts.forEachChild(node, visit);
	}
	visit(source);
}

walk(join(sourceRoot, 'vs'));
for (const key of conflicts) messages.delete(key);
const out = join(sourceRoot, 'vs/nls.ko.ts');
const entries = Object.fromEntries([...messages].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
writeFileSync(out, `// Generated by source/JBroScriptEditor/scripts/generate-dev-korean.mjs.\n` +
	`// Source: microsoft/vscode-loc@0f157dee0cdcbf58cdf51a221ee94751c7f35e75 (MIT).\n` +
	`export const koMessages: Readonly<Record<string, string>> = ${JSON.stringify(entries)};\n`, 'utf8');
console.log(`Generated ${messages.size} development translations (${matched} matched calls, ${conflicts.size} ambiguous keys) in ${out}`);
